from __future__ import annotations
import json, zipfile
from pathlib import Path
from PIL import Image
from pcs.animation.engine import AnimationClip, create_spritesheet, render_frames
from pcs.engine.raster import render_vector
from pcs.engine.svg_writer import save_svg
from pcs.generator.character import CharacterConfig, build_character

def export_png(scene,path,scale=1.0):
    img=render_vector(scene,scale=scale,ss=3); img.save(path); return Path(path)
def export_animation(scene,clip,directory):
    out=Path(directory); out.mkdir(parents=True,exist_ok=True)
    frames=render_frames(scene,clip,scale=.5)
    for i,frame in enumerate(frames): frame.save(out/f'{clip.name}_{i:03}.png')
    sheet=create_spritesheet(frames)
    sheet.save(out/f'{clip.name}.png')
    return sheet, {'name':clip.name,'fps':clip.fps,'frame_count':len(frames),'loop':clip.loop,'frame_width':frames[0].width,'frame_height':frames[0].height,'columns':len(frames),'rows':1,'frames':[{'index':i,'x':i*frames[0].width,'y':0,'duration_ms':round(1000/clip.fps)} for i in range(len(frames))]}
def export_order(config: CharacterConfig, destination, animations=('idle','walking','attacking')):
    root=Path(destination); root.mkdir(parents=True,exist_ok=True); scene=build_character(config)
    character=root/'character'; character.mkdir(exist_ok=True)
    save_svg(scene,character/'character.svg'); export_png(scene,character/'character.png',1.0)
    config.save(character/'character.json')
    animdir=root/'animations'; animdir.mkdir(exist_ok=True)
    sheetdir=root/'spritesheets'; sheetdir.mkdir(exist_ok=True)
    metadata={}; all_frames=[]
    for name in animations:
        clip=AnimationClip(name,12,12,name in ('idle','walking'))
        sheet,meta=export_animation(scene,clip,animdir); metadata[name]=meta
        # preserve individual sprite strips under animation-specific names
        (animdir/f'{name}_metadata.json').write_text(json.dumps(meta,indent=2),encoding='utf-8')
        all_frames.extend(render_frames(scene,clip,scale=.5))
    if all_frames:
        create_spritesheet(all_frames,columns=12).save(sheetdir/'character_spritesheet.png')
        (animdir/'animations.json').write_text(json.dumps(metadata,indent=2),encoding='utf-8')
    # Include a genuine animated magic effect preview, generated locally.
    from pcs.effects.procedural import add_effect
    fxdir=root/'effects'; fxdir.mkdir(exist_ok=True)
    effect_frames=[]
    for frame_index in range(8):
        fxscene=build_character(config)
        add_effect(fxscene,'magic',intensity=.72+frame_index*.06,particles=12,seed=config.seed+frame_index)
        effect_frames.append(render_vector(fxscene,scale=.5,ss=2))
    effect_frames[0].save(fxdir/'magic_effect.gif',save_all=True,append_images=effect_frames[1:],duration=100,loop=0,disposal=2)
    render_vector(fxscene,scale=.5,ss=2).save(fxdir/'magic_effect.png')
    previews=root/'previews'; previews.mkdir(exist_ok=True)
    render_vector(scene,scale=.5,ss=2).save(previews/'character_preview.png')
    if all_frames:
        all_frames[0].save(previews/'animation_preview.gif',save_all=True,append_images=all_frames[1:],duration=83,loop=0,disposal=2)
    docs=root/'documentation'; docs.mkdir(exist_ok=True)
    (docs/'import_into_godot.txt').write_text('Import the PNG spritesheet as a texture. Create a SpriteFrames resource, add animations using animations/animations.json frame coordinates, and set FPS from the metadata. Transparent PNG frames use uniform dimensions.\n',encoding='utf-8')
    (docs/'asset_license.txt').write_text('Original procedural vector artwork generated by Procedural Character Studio. You may use the delivered files in your own commercial game project. The generator software itself is not included in this usage grant. No third-party character artwork is bundled.\n',encoding='utf-8')
    (root/'README.txt').write_text(f"CLIENT DELIVERY\nCharacter: {config.name}\nIncludes SVG source, transparent PNG, JSON configuration, animation strips, sprite sheet, previews, effect and Godot import notes.\n",encoding='utf-8')
    # Remove empty directories/files and zip the complete portable delivery.
    zip_path=root.parent/(root.name+'.zip')
    with zipfile.ZipFile(zip_path,'w',zipfile.ZIP_DEFLATED) as z:
        for file in sorted(root.rglob('*')):
            if file.is_file() and file.stat().st_size: z.write(file,file.relative_to(root.parent))
    return zip_path
